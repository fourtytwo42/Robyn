"""Validate Robyn user stories and generate PRD traceability."""

from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PRD = ROOT / "prd"
STORIES = ROOT / "user-stories"
OUTPUT = STORIES / "TRACEABILITY.md"

REQ_RE = re.compile(r"\b(?:CORE|CREATE|DISC|TRADE|REWARD|PROTO|EXEC|DATA|INFRA|SEC|LEGAL|OPS|ANALYTICS|DESIGN|STACK)-\d{3}\b")
STORY_RE = re.compile(r"^### (US-[A-Z]+-\d{3}): (.+)$", re.MULTILINE)
PRD_DEF_RE = re.compile(r"^\| ((?:CORE|CREATE|DISC|TRADE|REWARD|PROTO|EXEC|DATA|INFRA|SEC|LEGAL|OPS|ANALYTICS|DESIGN|STACK)-\d{3}) \|", re.MULTILINE)


def main() -> None:
    requirements: dict[str, str] = {}
    for path in sorted(PRD.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        for req in PRD_DEF_RE.findall(text):
            if req in requirements:
                raise SystemExit(f"Duplicate PRD definition: {req}")
            requirements[req] = path.name

    stories: dict[str, dict] = {}
    coverage: dict[str, list[str]] = defaultdict(list)
    errors: list[str] = []
    for path in sorted(STORIES.glob("[0-9][0-9]-*.md")):
        text = path.read_text(encoding="utf-8")
        matches = list(STORY_RE.finditer(text))
        for index, match in enumerate(matches):
            story_id, title = match.groups()
            end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
            block = text[match.start():end]
            if story_id in stories:
                errors.append(f"Duplicate story ID: {story_id}")
            prd_line = re.search(r"^- PRD: (.+)$", block, re.MULTILINE)
            mapped = sorted(set(REQ_RE.findall(prd_line.group(1) if prd_line else "")))
            unknown = [req for req in mapped if req not in requirements]
            if unknown:
                errors.append(f"{story_id} references unknown requirements: {unknown}")
            for field in ("Release", "Priority", "Persona", "PRD", "Depends on"):
                if not re.search(rf"^- {field}: .+", block, re.MULTILINE):
                    errors.append(f"{story_id} missing {field}")
            if not re.search(r"^As .+, (?:I|we) want ", block, re.MULTILINE) or "Acceptance criteria:" not in block:
                errors.append(f"{story_id} missing story statement or acceptance criteria")
            if len(re.findall(r"^\d+\. ", block, re.MULTILINE)) < 2:
                errors.append(f"{story_id} needs at least two acceptance criteria")
            stories[story_id] = {"title": title, "file": path.name, "requirements": mapped}
            for req in mapped:
                coverage[req].append(story_id)

    uncovered = sorted(set(requirements) - set(coverage))
    if uncovered:
        errors.append(f"Uncovered PRD requirements: {', '.join(uncovered)}")

    lines = [
        "# PRD-to-user-story traceability",
        "",
        "Generated by `scripts/validate-user-stories.py`. Do not edit manually.",
        "",
        f"- PRD requirements: {len(requirements)}",
        f"- User stories: {len(stories)}",
        f"- Requirements covered: {len(coverage)}",
        f"- Uncovered requirements: {len(uncovered)}",
        "",
        "| PRD requirement | PRD document | Covering stories |",
        "|---|---|---|",
    ]
    for req in sorted(requirements):
        links = ", ".join(
            f"[{story_id}]({stories[story_id]['file']}#{story_id.lower()})"
            for story_id in coverage.get(req, [])
        ) or "None"
        lines.append(f"| `{req}` | [source](../prd/{requirements[req]}) | {links} |")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    if errors:
        raise SystemExit("\n".join(errors))
    print(f"Validated {len(stories)} stories covering {len(coverage)}/{len(requirements)} requirements")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
